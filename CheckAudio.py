#!/usr/bin/env python3
"""Inventory local VoiceOver audio without editing recordings or accessing the network.

Optional cross-platform alternative to CheckAudio.cmd/CheckAudio.ps1.
Run with Python 3.9+ after placing the original EN/RU audio in this addon.
Checks filenames, extensions, folder and nonzero size, not language or decoding.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import sys
from datetime import datetime

ENTRY = re.compile(r'^\s*\["(?P<key>[a-z0-9-]+)"\]\s*=\s*(?P<duration>[0-9]+(?:\.[0-9]+)?)', re.M)
QUEST = re.compile(r'^(?:[mf]-)?[0-9]+-(?:accept|progress|complete)$')


def read_lengths(path: Path) -> dict[str, float]:
    result: dict[str, float] = {}
    for match in ENTRY.finditer(path.read_text(encoding='utf-8-sig')):
        key, duration = match['key'], float(match['duration'])
        if key in result or duration <= 0:
            raise ValueError(f'Invalid or duplicate manifest entry: {key}')
        result[key] = duration
    if not result:
        raise ValueError(f'No valid manifest entries: {path}')
    return result


def read_audio(root: Path, language: str, manifest: dict[str, float]):
    found: dict[str, str] = {}
    counts = dict(unknown=0, duplicates=0, wrong_folder=0, noncanonical=0)
    preferred = 'ogg' if language == 'ru' else 'mp3'
    for folder in ('quests', 'gossip'):
        location = root / 'generated' / 'sounds' / language / folder
        if not location.is_dir():
            continue
        for file in sorted(location.iterdir()):
            if not file.is_file():
                continue
            ext, key = file.suffix.lstrip('.').lower(), file.stem.lower()
            if ext not in ('mp3', 'ogg'):
                continue
            if key not in manifest:
                counts['unknown'] += 1
                continue
            expected = 'quests' if QUEST.fullmatch(key) else 'gossip'
            if folder != expected:
                counts['wrong_folder'] += 1
                continue
            if file.stat().st_size <= 0:
                continue
            # The Lua module uses canonical lower-case names. On case-sensitive
            # filesystems do not advertise a path that is not actually present.
            if not (location / (key + '.' + ext)).is_file():
                counts['noncanonical'] += 1
                continue
            if key in found:
                counts['duplicates'] += 1
                if ext == preferred:
                    found[key] = ext
            else:
                found[key] = ext
    return found, counts


def select(key: str, manifests, installed):
    neutral = key[2:] if key.startswith(('m-', 'f-')) else None
    candidates = [('ru', key)]
    if neutral:
        candidates.append(('ru', neutral))
    candidates.append(('en', key))
    if neutral:
        candidates.append(('en', neutral))
    for language, source in candidates:
        if source in manifests[language] and source in installed[language]:
            return language, source
    return None


def inventory_addon(root: Path) -> dict[str, int]:
    root = root.resolve()
    manifests = {
        'en': read_lengths(root / 'generated' / 'sound_length_table.lua'),
        'ru': read_lengths(root / 'generated' / 'sound_length_table_ru.lua'),
    }
    scans = {lang: read_audio(root, lang, manifest) for lang, manifest in manifests.items()}
    installed = {lang: scan[0] for lang, scan in scans.items()}
    if not any(installed.values()):
        raise ValueError('No known nonempty media files. Copy quests/gossip into '
                         'generated/sounds/en and generated/sounds/ru, without an extra sounds folder. '
                         'Inventory was NOT changed.')
    counts = dict(en=0, ru=0, missing=0, aliases=0)
    missing = []
    for key in sorted(set(manifests['en']) | set(manifests['ru'])):
        selected = select(key, manifests, installed)
        if selected:
            language, source = selected
            counts[language] += 1
            counts['aliases'] += int(source != key)
        else:
            counts['missing'] += 1
            missing.append(key)
    lines = [
        '-- Generated by CheckAudio.py from actual local filenames.',
        '-- Re-run the checker whenever audio files change.',
        'if not VoiceOver or not VoiceOver.DataModules then return end',
        'AI_VoiceOverData_Vanilla.HybridInstalledFiles = {',
    ]
    for language in ('en', 'ru'):
        lines.append(f'    ["{language}"] = {{')
        for key, ext in sorted(installed[language].items()):
            lines.append(f'        ["{key}"] = "{ext}",')
        lines.append('    },')
    lines.append('}')
    target = root / 'generated' / 'installed_audio.lua'
    temporary = target.with_suffix('.lua.tmp')
    temporary.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    os.replace(temporary, target)
    report = [
        'VoiceOver base EN UI / RU first / EN fallback - local inventory before CatQuest overlay',
        'Checked: ' + datetime.now().isoformat(timespec='seconds'),
    ]
    for language in ('en', 'ru'):
        report.append(f'{language.upper()} manifest entries: {len(manifests[language])}')
        report.append(f'{language.upper()} known media files found: {len(installed[language])}')
        report.append(f'{language.upper()} scan diagnostics: {scans[language][1]}')
    report += [
        f'Selected RU lookup keys: {counts["ru"]}',
        f'Selected EN fallback lookup keys: {counts["en"]}',
        f'Neutral aliases: {counts["aliases"]}',
        f'Unavailable lookup keys: {counts["missing"]}',
        'Checks names, nonzero size, extensions and location, NOT audio language/content or decoding.',
        'Durations are taken from the supplied manifests, not remeasured.',
        '',
        'No eligible audio for these keys:' if missing else 'All manifest keys have an audio-path candidate.',
        *missing,
    ]
    (root / 'audio_check.txt').write_text('\n'.join(report) + '\n', encoding='utf-8')
    return counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--addon-root', type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    try:
        counts = inventory_addon(args.addon_root)
    except (OSError, ValueError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return 1
    print(f'Routes: RU={counts["ru"]}; EN fallback={counts["en"]}; '
          f'unavailable={counts["missing"]}; neutral aliases={counts["aliases"]}')
    print('Wrote generated/installed_audio.lua and audio_check.txt. Start WoW or /reload.')
    print('Re-run the checker after changing audio files.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
