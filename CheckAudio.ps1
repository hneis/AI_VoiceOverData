# Local-only audio inventory for the EN UI / RU-first VoiceOver data module.
# Reads the two supplied manifests and actual media directories.
# Writes only generated\installed_audio.lua and audio_check.txt in this addon.
# Does not delete audio, change client settings, download files or need admin rights.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$addonRoot = $PSScriptRoot
$culture = [System.Globalization.CultureInfo]::InvariantCulture
$utf8 = New-Object -TypeName System.Text.UTF8Encoding -ArgumentList $false

function Read-Lengths([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "Manifest not found: $Path"
    }
    $text = [System.IO.File]::ReadAllText($Path)
    $pattern = '^\s*\["(?<key>[a-z0-9-]+)"\]\s*=\s*(?<duration>[0-9]+(?:\.[0-9]+)?)'
    $matches = [regex]::Matches($text, $pattern, [System.Text.RegularExpressions.RegexOptions]::Multiline)
    $result = @{}
    foreach ($match in $matches) {
        $key = $match.Groups['key'].Value
        $duration = [double]::Parse($match.Groups['duration'].Value, $culture)
        if ($result.ContainsKey($key)) { throw "Duplicate manifest key: $key" }
        if ($duration -le 0) { throw "Invalid duration for: $key" }
        $result[$key] = $duration
    }
    if ($result.Count -eq 0) { throw "No valid entries in manifest: $Path" }
    return $result
}

function Read-Audio([string]$Language, [hashtable]$Manifest) {
    $found = @{}
    $unknown = 0
    $duplicates = 0
    $wrongFolder = 0
    $preferred = 'mp3'
    if ($Language -eq 'ru') { $preferred = 'ogg' }
    foreach ($folder in @('quests', 'gossip')) {
        $path = Join-Path $addonRoot "generated\sounds\$Language\$folder"
        if (-not (Test-Path -LiteralPath $path -PathType Container)) { continue }
        foreach ($file in @(Get-ChildItem -LiteralPath $path -File)) {
            $ext = $file.Extension.TrimStart('.').ToLowerInvariant()
            if ($ext -ne 'mp3' -and $ext -ne 'ogg') { continue }
            $key = $file.BaseName.ToLowerInvariant()
            if (-not $Manifest.ContainsKey($key)) { $unknown++; continue }
            $expectedFolder = 'gossip'
            if ($key -cmatch '^(?:[mf]-)?[0-9]+-(?:accept|progress|complete)$') {
                $expectedFolder = 'quests'
            }
            if ($folder -ne $expectedFolder) { $wrongFolder++; continue }
            if ($file.Length -le 0) { continue }
            if ($found.ContainsKey($key)) {
                $duplicates++
                if ($ext -eq $preferred) { $found[$key] = $ext }
            } else {
                $found[$key] = $ext
            }
        }
    }
    return @{ Files = $found; Unknown = $unknown; Duplicates = $duplicates; WrongFolder = $wrongFolder }
}

try {
    $en = Read-Lengths (Join-Path $addonRoot 'generated\sound_length_table.lua')
    $ru = Read-Lengths (Join-Path $addonRoot 'generated\sound_length_table_ru.lua')
    $enScan = Read-Audio 'en' $en
    $ruScan = Read-Audio 'ru' $ru
    $installed = @{ en = $enScan.Files; ru = $ruScan.Files }
    $manifests = @{ en = $en; ru = $ru }
    if ($installed.en.Count -eq 0 -and $installed.ru.Count -eq 0) {
        throw 'No known audio files found. Copy quests/gossip into generated\sounds\en and generated\sounds\ru. Do not create an extra sounds subfolder. Inventory was NOT changed.'
    }

    $allKeys = @{}
    foreach ($key in $en.Keys) { $allKeys[$key] = $true }
    foreach ($key in $ru.Keys) { $allKeys[$key] = $true }
    $counts = @{ en = 0; ru = 0; missing = 0; aliases = 0 }
    $missingKeys = New-Object 'System.Collections.Generic.List[string]'
    foreach ($key in ($allKeys.Keys | Sort-Object)) {
        $neutral = $null
        if ($key -cmatch '^[mf]-') { $neutral = $key.Substring(2) }
        $candidates = @(@{ Language = 'ru'; Key = $key })
        if ($null -ne $neutral) { $candidates += @{ Language = 'ru'; Key = $neutral } }
        $candidates += @{ Language = 'en'; Key = $key }
        if ($null -ne $neutral) { $candidates += @{ Language = 'en'; Key = $neutral } }
        $selected = $false
        foreach ($candidate in $candidates) {
            $lang = $candidate.Language
            $sourceKey = $candidate.Key
            if ($manifests[$lang].ContainsKey($sourceKey) -and $installed[$lang].ContainsKey($sourceKey)) {
                $counts[$lang]++
                if ($sourceKey -cne $key) { $counts.aliases++ }
                $selected = $true
                break
            }
        }
        if (-not $selected) { $counts.missing++; $missingKeys.Add($key) }
    }

    $lines = New-Object 'System.Collections.Generic.List[string]'
    $lines.Add('-- Generated by CheckAudio.ps1 from actual local filenames.')
    $lines.Add('-- Re-run the checker after adding, removing or moving media.')
    $lines.Add('if not VoiceOver or not VoiceOver.DataModules then return end')
    $lines.Add('AI_VoiceOverData_Vanilla.HybridInstalledFiles = {')
    foreach ($lang in @('en', 'ru')) {
        $lines.Add('    ["' + $lang + '"] = {')
        foreach ($key in ($installed[$lang].Keys | Sort-Object)) {
            $lines.Add('        ["' + $key + '"] = "' + $installed[$lang][$key] + '",')
        }
        $lines.Add('    },')
    }
    $lines.Add('}')
    $inventoryPath = Join-Path $addonRoot 'generated\installed_audio.lua'
    $temporaryPath = $inventoryPath + '.tmp'
    [System.IO.File]::WriteAllLines($temporaryPath, $lines.ToArray(), $utf8)
    Move-Item -LiteralPath $temporaryPath -Destination $inventoryPath -Force

    $report = New-Object 'System.Collections.Generic.List[string]'
    $report.Add('VoiceOver EN UI / RU first / EN fallback - local audio inventory')
    $report.Add('Checked: ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
    $report.Add('EN manifest entries: ' + $en.Count)
    $report.Add('RU manifest entries: ' + $ru.Count)
    $report.Add('EN known media files found: ' + $installed.en.Count)
    $report.Add('RU known media files found: ' + $installed.ru.Count)
    $report.Add('Selected RU lookup keys: ' + $counts.ru)
    $report.Add('Selected EN fallback lookup keys: ' + $counts.en)
    $report.Add('Neutral aliases: ' + $counts.aliases)
    $report.Add('Unavailable lookup keys: ' + $counts.missing)
    $report.Add('Ignored unlisted audio filenames: ' + ($enScan.Unknown + $ruScan.Unknown))
    $report.Add('Known audio in wrong quests/gossip folder: ' + ($enScan.WrongFolder + $ruScan.WrongFolder))
    $report.Add('Duplicate formats for the same key: ' + ($enScan.Duplicates + $ruScan.Duplicates))
    $report.Add('The check verifies filenames, nonzero size and extensions, NOT audio language/content or decoding.')
    $report.Add('Durations come from the supplied manifests; audio is not regenerated or remeasured.')
    $report.Add('')
    if ($counts.missing -gt 0) {
        $report.Add('No eligible audio file for these keys:')
        foreach ($key in $missingKeys) { $report.Add($key) }
    } else {
        $report.Add('All manifest lookup keys have a playable-path candidate.')
    }
    [System.IO.File]::WriteAllLines((Join-Path $addonRoot 'audio_check.txt'), $report.ToArray(), $utf8)
    Write-Host ('EN media found: {0}; RU media found: {1}' -f $installed.en.Count, $installed.ru.Count)
    Write-Host ('Routes: RU={0}; EN fallback={1}; unavailable={2}; neutral aliases={3}' -f $counts.ru, $counts.en, $counts.missing, $counts.aliases)
    if ($installed.en.Count -eq 0) { Write-Warning 'EN audio is absent: fallback cannot cover missing RU recordings.' }
    if ($installed.ru.Count -eq 0) { Write-Warning 'RU audio is absent: the available recordings will use EN.' }
    if ($counts.missing -gt 0) { Write-Warning 'Some keys have no available audio. See audio_check.txt.' }
    Write-Host 'Updated generated\installed_audio.lua. Start WoW, or /reload if it was already running.'
    Write-Host 'Re-run this checker whenever you change the audio folders.'
    exit 0
} catch {
    Write-Error $_ -ErrorAction Continue
    exit 1
}
