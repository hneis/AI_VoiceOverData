#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

function compactText(text) {
    const words = String(text || "").trim().split(/\s+/).filter(Boolean);
    return words.slice(0, 15).join(" ") + " " + words.slice(-15).join(" ");
}

function luaString(value) {
    return '"' + value.replace(/[\\"\x00-\x1f\x7f]/g, character => {
        if (character === "\\" || character === '"') return "\\" + character;
        return "\\" + character.charCodeAt(0).toString().padStart(3, "0");
    }) + '"';
}

function ambiguousBaseTitles(file) {
    const source = fs.readFileSync(file, "utf8");
    const acceptStart = source.indexOf('["accept"]');
    const completeStart = source.indexOf('\n\t["complete"]', acceptStart);
    if (acceptStart < 0 || completeStart < 0) throw new Error("Cannot isolate the accept lookup table");
    const acceptSource = source.slice(acceptStart, completeStart);
    const titles = new Set();
    for (const match of acceptSource.matchAll(/^\t\t\["((?:\\.|[^"])*)"\]\s*=\s*\{/gm)) {
        titles.add(match[1].replace(/\\"/g, '"').replace(/\\\\/g, "\\"));
    }
    return titles;
}

function main() {
    const localesFile = process.argv[2];
    const baseLookupFile = process.argv[3];
    const outputFile = process.argv[4] || path.resolve(__dirname, "..", "generated", "octo_quest_text_lookups.lua");
    const sourceRevision = process.argv[5] || "unknown";
    if (!localesFile || !baseLookupFile) {
        throw new Error("Usage: node tools/build_octowow_quest_text_lookup.js <locales.json> <quest_id_lookups.lua> [output.lua] [source-revision]");
    }

    const quests = JSON.parse(fs.readFileSync(localesFile, "utf8")).quests;
    const baseTitles = ambiguousBaseTitles(baseLookupFile);
    const grouped = new Map();
    for (const [rawID, quest] of Object.entries(quests)) {
        const id = Number(rawID);
        if (!Number.isInteger(id) || id <= 0 || !quest || !quest.T || !quest.D || !baseTitles.has(quest.T)) continue;
        if (!grouped.has(quest.T)) grouped.set(quest.T, []);
        grouped.get(quest.T).push({ id, text: compactText(quest.D).replace(/"/g, "'") });
    }

    const titles = [];
    let routeCount = 0, blockedCount = 0;
    for (const [title, records] of grouped) {
        if (records.length < 2) continue;
        const byText = new Map();
        for (const record of records) {
            if (!byText.has(record.text)) byText.set(record.text, []);
            byText.get(record.text).push(record.id);
        }
        const routes = [];
        for (const [text, ids] of byText) {
            const uniqueIDs = Array.from(new Set(ids));
            const id = uniqueIDs.length === 1 ? uniqueIDs[0] : 0;
            routes.push({ text, id });
            if (id) routeCount++;
            else blockedCount++;
        }
        routes.sort((left, right) => left.text.localeCompare(right.text, "en"));
        titles.push({ title, routes });
    }
    titles.sort((left, right) => left.title.localeCompare(right.title, "en"));

    const lines = [
        "-- Generated by tools/build_octowow_quest_text_lookup.js; do not edit manually.",
        "-- ID 0 marks text that is not unique and must not fall back to another quest stage.",
        "AI_VoiceOverData_Vanilla.OctoQuestTextLookup = {",
        "    SchemaVersion = 1,",
        `    SourceRevision = ${luaString(sourceRevision)},`,
        `    TitleCount = ${titles.length},`,
        `    RouteCount = ${routeCount},`,
        `    BlockedCount = ${blockedCount},`,
        "    Routes = {",
    ];
    for (const entry of titles) {
        lines.push(`        [${luaString(entry.title)}] = {`);
        for (const route of entry.routes) lines.push(`            [${luaString(route.text)}] = ${route.id},`);
        lines.push("        },");
    }
    lines.push("    },", "}", "");
    fs.writeFileSync(outputFile, lines.join("\n"));
    console.log(`Wrote ${outputFile}: ${titles.length} titles, ${routeCount} unique routes, ${blockedCount} blocked texts`);
}

main();
